-- ‏משפך סקר התשלום · ארבעה שלבים, כל אחד נספר בנפרד
--
-- ⭐ **המשפט לחגי:** עכשיו אפשר לדעת בכל שלב כמה אנשים נפלו · כמה סיימו סבב,
--    כמה מהם ראו את הכרטיס, וכמה מאלה שראו בכלל נגעו בו.
--
-- ⛔ בטיחות: `select` בלבד. אפס INSERT · UPDATE · DELETE · שינוי סכימה.
--    הפלט **מספרים בלבד** · אפס מיילים ואפס מזהי משתמש.
--
-- ⚠ **תנאי מוקדם:** `supabase/wtp-kind-migration.sql` הורץ, והקוד החדש באוויר.
--    בלי שניהם השאילתה תיתן אפס בכל השלבים · וזה יאמר «עוד לא נמדד», לא «אפס אנשים».
--
-- ═══════════════════════════════════════════════════════════════════════
-- ⛔ שני מכנים נוסו לפני זה, ושניהם היו שגויים · כדי שלא ינוסו שוב
-- ═══════════════════════════════════════════════════════════════════════
--
-- ⛔ `data->'stats' <> '{}'::jsonb`  ·  **תמיד־אמת.** `stats` מאותחל ל-
--    `{words:{},sessions:[]}` (`app.js:112`) ונשלח כך. הוא מדד «יש שורת
--    התקדמות». זו הסיבה ששני מספרי הבקרה יצאו זהים · 47 = 47.
--
-- ⛔ `jsonb_array_length(data->'stats'->'sessions') > 0`  ·  **נופל מאותה סיבה.**
--    `finishRound` (`app.js:2571`) **אינו** קורא ל-`commitSession`; היא נקראת
--    משמונה מקומות אחרים, והשורה ב-`sessions` נוצרת **בקומיט הראשון**
--    (`app.js:2873`). כלומר מי שענה על 3 מילים מתוך 20 וסגר לשונית מקבל אחת,
--    ומעולם לא הגיע לנקודה.
--
-- ⭐ **המכנה היחיד שנכתב ברגע הנכון הוא זה שנכתב מהקוד שמגיע לרגע הזה** ·
--    `Store.wtpMarkReached()`, נקרא מ-`finishRound` עצמו.

with u as (
  select user_id,
         max((kind = 'reached')::int)                                as הגיע,
         max((kind = 'shown')::int)                                  as הוצג,
         max((kind = 'answer'  or (kind is null and price_bucket is not null))::int) as ענה,
         max((kind = 'dismiss' or (kind is null and price_bucket is null
                                   and dismissed = true))::int)      as סגר
    from public.wtp_survey
   group by user_id
)
-- ⚠ `kind is null` הוא שורה מלפני העמודה · כולן תגובות, ולכן הן נספרות ככאלה.
--    זו הסיבה שחלק 3 במיגרציה (מילוי השמות הישנים) אינו חובה.
select
  -- ⭐ בקרה · חייב > 0, אחרת השאילתה לא רצה
  (select count(*) from auth.users)                          as סהכ_משתמשים,

  -- ⭐ ארבעת השלבים · כל אחד ספירת **אנשים**
  (select count(*) from u where הגיע = 1)                    as הגיעו_לנקודה,
  (select count(*) from u where הוצג = 1)                    as ראו_את_הכרטיס,
  (select count(*) from u where ענה = 1)                     as ענו,
  (select count(*) from u where סגר = 1)                     as סגרו_ב_✕,

  -- ⭐ **ושתי הנפילות · זה מה שלא היה אפשר לדעת**
  (select count(*) from u where הגיע = 1 and הוצג = 0)       as הגיעו_ולא_הוצג,
  (select count(*) from u where הוצג = 1 and ענה = 0 and סגר = 0)
                                                             as ראו_ולא_הגיבו,

  -- אירועים, לא אנשים · כמה פעמים בסך הכול
  (select count(*) from public.wtp_survey where kind = 'reached') as אירועי_סיום_סבב,
  (select count(*) from public.wtp_survey where kind = 'shown')   as אירועי_הצגה;

-- ═══════════════════════════════════════════════════════════════════════
-- ‏איך לקרוא
-- ═══════════════════════════════════════════════════════════════════════
--
--   `הגיעו_ולא_הוצג` גבוה     →  החסם הוא **לפני** ההצגה. שלושת החשודים:
--                                 חלון השתי־שניות · «כבר נשאל» · מנותק.
--   `ראו_ולא_הגיבו` גבוה      →  ההצגה עובדת, וההיענות היא הבעיה.
--   `אירועי_סיום_סבב` ≫ אנשים →  מעט אנשים מסיימים הרבה סבבים.
--                                 ⚠ ואם `ראו_את_הכרטיס` נמוך למרות זאת —
--                                 זה בדיוק הדגל שנדלק פעם אחת לטעינת עמוד.
--
-- ⛔ **וכל עוד `אירועי_סיום_סבב` = 0 · אין להסיק כלום.** זה אומר שהקוד עדיין
--    לא באוויר או שהמדיניות חוסמת את השורות, **לא שאיש לא סיים סבב.**
--    במקרה כזה · חזור לחלק 2 במיגרציה.


-- ═══════════════════════════════════════════════════════════════════════
-- ⚠ שאילתה שנייה · המדיניות. הרץ אותה אם השלבים החדשים מראים אפס
-- ═══════════════════════════════════════════════════════════════════════
--
-- ⛔ ההשערה «RLS חוסם את הסקר לכולם» **הופרכה** · 17 שורות קיימות, וכל אחת
--    נכתבת רק ממגע בכרטיס מוצג. חסימה גורפת הייתה נותנת אפס.
-- ⭐ אבל שתי הכתיבות החדשות הן INSERT של שורה **בלי תשובה**, וזו צורה שלא
--    נוסתה מעולם. אם `with_check` מתנה משהו על `price_bucket` או על `kind` ·
--    השורות לא ייכתבו, בשקט.

select policyname, cmd, roles, qual, with_check
  from pg_policies
 where schemaname = 'public' and tablename = 'wtp_survey'
 order by cmd;
