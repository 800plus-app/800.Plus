-- ‏יחס הדחיות בסקר התשלום · לפני ואחרי · עם ספירת החשיפות החדשות
--
-- ⭐ **המשפט לחגי:** סופר כמה אנשים ראו את כרטיס המחיר וסגרו אותו בלי לענות,
--    ומפריד בין מה שהיה לפני השינוי לבין מה שקרה אחריו.
--
-- ⛔ בטיחות: `select` בלבד. אפס INSERT · UPDATE · DELETE · GRANT · שינוי סכימה.
--    הפלט מספרים בלבד · אפס מיילים ואפס מזהי משתמש.
--
-- ══════════════════════════════════════════════════════════════════════
-- ⛔ שנה שורה אחת לפני ההרצה
-- ══════════════════════════════════════════════════════════════════════
-- ‏`CUTOFF` למטה הוא התאריך שבו הכרטיס שונה. עד שיש שינוי · להשאיר תאריך
-- ‏עתידי, ואז הכול ייפול ל«לפני» וזה המצב הנוכחי.


-- ══════════════════════════════════════════════════════════════════════
-- ‏1 · התמונה · לפני · אחרי · וההפרש
-- ══════════════════════════════════════════════════════════════════════
with cfg as (select timestamptz '2099-01-01' as cutoff),   -- ⬅ ⛔ שנה כאן
s as (
  select case when answered_at < (select cutoff from cfg) then 'לפני' else 'אחרי' end as תקופה,
         price_bucket is not null as ענה,
         dismissed
    from public.wtp_survey
)
select תקופה,
       count(*)                                              as חשיפות,
       count(*) filter (where ענה)                           as ענו,
       count(*) filter (where not ענה)                       as סגרו_בלי_לענות,
       round(100.0 * count(*) filter (where not ענה) / nullif(count(*),0), 1)
                                                             as אחוז_דחייה,
       -- ⭐ בקרת עקביות · שתי הדרכים לספור דחייה חייבות להסכים
       count(*) filter (where dismissed)                     as מסומן_dismissed,
       count(*) filter (where dismissed <> (not ענה))        as סתירה_בין_השניים
  from s
 group by תקופה
 order by תקופה desc;

-- ⭐ איך קוראים:
--   חשיפות בתקופת «אחרי» < 15   →  ⛔ **אין מסקנה.** המדד דורש 15 לפחות
--   אחוז_דחייה «אחרי» < 50      →  ⭐ שיפור
--   סתירה_בין_השניים > 0        →  ⛔ **הנתון עצמו לא עקבי** · אל תסיק כלום
--
-- ⚠ `סתירה_בין_השניים` היא הבקרה החשובה: `dismissed` הוא עמודה מפורשת,
--    ו«אין מחיר» הוא היסק. אם הם לא מסכימים · אחד מהם אינו מה שחשבנו.


-- ══════════════════════════════════════════════════════════════════════
-- ‏2 · הבקרה · שהשאילתה בכלל רצה על נתונים
-- ══════════════════════════════════════════════════════════════════════
select (select count(*) from public.wtp_survey)                          as סך_שורות,
       (select count(*) from public.wtp_survey where answered_at is null) as בלי_תאריך,
       (select min(answered_at)::date from public.wtp_survey)             as הראשונה,
       (select max(answered_at)::date from public.wtp_survey)             as האחרונה;
-- ⛔ `סך_שורות = 0` פירושו שהמדידה שבורה, לא ש«אף אחד לא ראה».
-- ⚠ `בלי_תאריך > 0` פירושו ששורות כאלה נופלות ל«אחרי» בחלוקה למעלה · ואז
--    הפילוח מטעה. ⭐ העמודה קיימת כדי שזה ייראה ולא יישאר שקט.


