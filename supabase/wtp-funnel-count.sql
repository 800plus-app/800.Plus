-- ‏כמה הגיעו לנקודת הסקר · מול כמה ראו אותו
--
-- ⭐ **המשפט לחגי:** השאילתה סופרת כמה לומדים בכלל סיימו סבב ולכן היו זכאים
--    לראות את סקר התשלום, מול כמה באמת ראו אותו · כדי לדעת אם «16» נמוך כי
--    מעט הגיעו, או כי משהו חסם אותם בדרך.
--
-- ⛔ בטיחות: `select` בלבד. אפס INSERT · UPDATE · DELETE · שינוי סכימה.
--    הפלט הוא **מספרים בלבד** · אפס מיילים ואפס מזהי משתמש.
--
-- ‏התנאי כפי שהוא בקוד היום (`app.js` · `maybeAskWtp`, אחרי התיקון מ-26.8):
-- ‏הסקר נקרא בכל סיום סבב, ומופיע אם הלומד מחובר · נשאר במסך התוצאות שתי
-- ‏שניות · ואין לו שורה ב-`wtp_survey`. הדגל `wtpShown` נדלק **רק בהצגה בפועל**.

select
  -- ⭐ בקרה 1 · חייב לחזור > 0, אחרת השאילתה לא באמת רצה
  (select count(*) from auth.users)                                as סהכ_משתמשים,

  -- ⭐ בקרה 2 · אם זה > 0 אבל «הגיעו_לנקודה» = 0, ההנחה על מבנה ה-stats שגויה
  --    ואין להסיק מהמספר הבא כלום
  (select count(distinct user_id) from progress)                   as יש_שורת_התקדמות,

  -- המספר הראשון · מי שסיים סבב ולכן היה זכאי לראות
  (select count(distinct user_id) from progress
    where jsonb_typeof(data->'stats') = 'object'
      and data->'stats' <> '{}'::jsonb)                            as הגיעו_לנקודה,

  -- המספר השני · מי שבאמת ראה. כל שורה כאן היא הצגה בפועל
  (select count(*) from wtp_survey)                                as ראו_את_הסקר,

  (select count(*) from wtp_survey where price_bucket is not null) as ענו,
  (select count(*) from wtp_survey where price_bucket is null)     as סגרו_בלי_לענות;

-- ‏איך לקרוא את התוצאה:
--   ‏«הגיעו_לנקודה» ≈ «ראו_את_הסקר»  →  אין חסימה. 16 נמוך כי מעט הגיעו.
--   ‏«הגיעו_לנקודה» ≫ «ראו_את_הסקר»  →  יש חסימה, והפער הוא גודלה.
--
-- ⚠ «הגיעו_לנקודה» הוא **חסם תחתון**: הוא סופר מי שיש לו stats מסונכרן, לא מי
--    שסיים סבב. מי שסיים ולא סנכרן (אופליין, יציאה מיידית) אינו נספר, ולכן פער
--    שיתגלה הוא לכל הפחות בגודל שיוצג.
