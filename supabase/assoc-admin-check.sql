-- ‏`migrations/3.sql:19-22` מגדיר:
--
--   create or replace function public.is_admin() returns boolean
--   language sql stable security definer set search_path = public as $$
--     select exists (select 1 from public.profiles
--                     where id = auth.uid() and role = 'admin');
--   $$;
--
-- ⛔ **היא אינה מקבלת ארגומנטים**, ואין בשום מיגרציה גרסה שמקבלת. ‏`is_admin(id)`
--    היה נופל ב-*function does not exist*.
-- ⛔ **ומעבר לחתימה · היא בודקת את `auth.uid()`**, כלומר את **הקורא**, ולא
--    משתמש שנמסר לה. גם אילו הייתה מקבלת ארגומנט, היא לא הייתה עונה על השאלה.
--
-- ⭐ **ולכן הבדיקה נעשית ישירות מול `profiles.role`** · בדיוק מה ש-`is_admin()`
--    עושה בפנים, רק על משתמש שנבחר ולא על הקורא.
--
-- ⚠ להריץ ב-SQL Editor, שרץ בתפקיד מורשה. ‏`profiles` תחת RLS, ומתפקיד
--    `authenticated` השאילתה הזאת הייתה מחזירה 0 · ⭐ **וזה עצמו יופיע
--    בבקרה למטה.**

select
  -- ⭐ הבקרה · חייב להיות > 0. אם 0 · המדידה שבורה, לא «אין אדמינים»
  (select count(*) from public.profiles where role = 'admin')      as כמה_אדמינים,

  -- ⭐ אותו ביטוי בחירה בדיוק כמו ב-rls-isolation-all-tables.sql
  exists (
    select 1 from public.profiles
     where id = (select user_id from public.assoc_shared
                  group by user_id order by count(*) desc, user_id limit 1)
       and role = 'admin'
  )                                                                as א_הוא_אדמין,

  -- ⭐ ובקרה שנייה · שהבחירה בכלל מצאה מישהו
  (select count(distinct user_id) from public.assoc_shared)        as משתמשים_בטבלה;

