-- ═══════════════════════════════════════════════════════════════════════
-- ‏4 · אימות · ⭐ הרץ אחרי 1, ושוב אחרי שהקוד החדש באוויר
-- ═══════════════════════════════════════════════════════════════════════

select
  (select count(*) from information_schema.columns
    where table_schema='public' and table_name='wtp_survey' and column_name='kind')
                                                          as העמודה_קיימת,   -- ⭐ חייב 1
  (select count(*) from public.wtp_survey)                as סהכ_שורות,      -- ⭐ בקרה · > 0
  (select count(*) from public.wtp_survey where kind is null)     as בלי_שם,
  (select count(*) from public.wtp_survey where kind = 'reached') as הגיעו,
  (select count(*) from public.wtp_survey where kind = 'shown')   as הוצג,
  (select count(*) from public.wtp_survey where kind = 'answer')  as ענו,
  (select count(*) from public.wtp_survey where kind = 'dismiss') as סגרו;

-- ⛔ **ואחרי שהקוד באוויר · אם `הגיעו` נשאר 0 בזמן ש-`סהכ_שורות` גדל, המדיניות
--    חוסמת את השורות החדשות.** חזור לחלק 2.
