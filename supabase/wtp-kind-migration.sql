-- ‏עמודת `kind` ל-`wtp_survey` · מה שהופך את משפך הסקר למדיד
--
-- ⭐ **המשפט לחגי:** עד היום נרשמה שורה רק כשמישהו **הגיב** לסקר. לכן אי אפשר
--    היה לדעת כמה בכלל הגיעו לנקודה, וכמה ראו את הכרטיס ולא נגעו בו. העמודה
--    הזאת מוסיפה שם לכל שורה, ואז אפשר לספור כל שלב בנפרד.
--
-- ⛔ **הרץ את החלקים לפי הסדר, ועצור בין 2 ל-3 כדי להסתכל בפלט.**

-- ═══════════════════════════════════════════════════════════════════════
-- ‏1 · העמודה  ·  ⭐ בטוח · לא נוגע באף שורה קיימת
-- ═══════════════════════════════════════════════════════════════════════
--
-- `if not exists` · אפשר להריץ פעמיים בלי נזק.
-- בלי `not null` ובלי ברירת מחדל: ‏17 השורות הקיימות נשארות עם `null`,
-- וזה **המידע הנכון** · לא ידוע איזה שלב הן היו, רק שהן תגובה.

alter table public.wtp_survey
  add column if not exists kind text;

comment on column public.wtp_survey.kind is
  'שלב במשפך: reached · shown · answer · dismiss. null = שורה מלפני 26.8.2026, תגובה.';

-- ═══════════════════════════════════════════════════════════════════════
-- ‏2 · ⛔ עצור כאן · בדיקת המדיניות
-- ═══════════════════════════════════════════════════════════════════════
--
-- הקוד החדש כותב שורות שאין בהן תשובה (`price_bucket is null`). אם מדיניות
-- ה-INSERT מתנה משהו על העמודות האלה · **השורות החדשות פשוט לא ייכתבו**,
-- והשאילתה תיתן אפס לנצח בלי שאיש ידע למה.
--
-- ⭐ **מה לחפש בפלט:** שורה עם `cmd = 'INSERT'`, ובעמודת `with_check` צריך
--    להופיע רק השוואה על `user_id` (משהו בנוסח `auth.uid() = user_id`).
--    ⛔ אם מוזכרים שם `price_bucket` · `dismissed` · או `kind` — **תגיד לי מה
--    כתוב שם לפני שממשיכים.** אל תשנה את המדיניות לבד.

select policyname, cmd, roles, qual, with_check
  from pg_policies
 where schemaname = 'public' and tablename = 'wtp_survey'
 order by cmd;

-- ═══════════════════════════════════════════════════════════════════════
-- ‏3 · ⚠ רשות · שמות לשורות הישנות
-- ═══════════════════════════════════════════════════════════════════════
--
-- ⛔ **זה החלק היחיד כאן שכותב לנתונים אמיתיים**, ולכן הוא נפרד ואפשר לדלג עליו.
-- הוא אינו משנה שום ערך קיים · הוא רק ממלא את `kind` הריק לפי מה שכבר בשורה.
--
-- ⭐ **ולא חייבים אותו.** שאילתת המשפך (`wtp-funnel-split.sql`) בנויה לעבוד
--    גם בלעדיו · היא מתייחסת ל-`kind is null` כאל תגובה, וזה מה שהן.
--
-- ‏17 שורות צפויות. אם המספר שחוזר גדול בהרבה — עצור, כי משהו בהנחה שגוי.

