function render(id, file) {
  const L = LENSES[id];
  if (!L) throw new Error('אין עדשה ' + id);
  let out = COMMON + '\n\n' + L.body;
  if (file) {
    out += '\n\n## הקובץ\n\n```\n' + fs.readFileSync(file, 'utf8').trim() + '\n```\n';
  }
  return out;
}

