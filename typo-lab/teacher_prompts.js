function build(lens, file) {
  const L = LENSES[lens];
  if (!L) throw new Error(`עדשה לא מוכרת · ${lens} · מותר ${Object.keys(LENSES).join(' ')}`);
  const parts = [`# שופט · עדשה ${lens} · ${L.he}`, '', L.q, '', COMMON, '', L.body];
  if (file) {
    const abs = path.resolve(file);
    const outp = path.join(path.dirname(path.dirname(abs)), 'verdict', path.basename(abs));
    const n = fs.readFileSync(abs, 'utf8').split(/\r?\n/).filter(x => x.trim()).length - 1;
    parts.push('', '## המשימה', '',
      `קרא את \`${abs}\` · **${n} פריטים**.`,
      `כתוב את הפסקים ל-\`${outp}\` · ${n} שורות, אחת לכל פריט, בפורמט שלמעלה.`,
      'אל תכתוב שום קובץ אחר ואל תיגע בשום קובץ אחר.');
  }
  return parts.join('\n');
}

