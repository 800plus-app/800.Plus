'use strict';
/* חיץ אמיתי לפני שהבאנר מבטיח מעבר לתשלום.
 *
 * למה הבדיקה הזאת קיימת
 * -----------------------
 * PAY_FROM הוא התאריך שממנו renderPayCountdown מתחיל להבטיח למשתמש "עוד יומיים
 * מתחיל התשלום" / "מחר מתחיל התשלום" / "היום מתחיל התשלום". מערכת הגבייה בפועל
 * אינה פרוסה (נמדד: ארבע פונקציות הענן מחזירות 404), ולכן PAY_FROM חייב להשאיר
 * חיץ אמיתי מהיום הנוכחי -- אחרת האפליקציה מבטיחה מעבר לתשלום שלא יקרה, וזה
 * בדיוק המשפט שגורם למשתמש להפסיק להאמין לשאר המסך.
 *
 * הבדיקה גוזרת את "היום" מהשעון האמיתי (new Date()) ולא מתאריך קבוע בקוד --
 * תאריך קבוע היה הופך את הבדיקה לפג-תוקף בעצמה: היא הייתה מפסיקה לבדוק משהו
 * אמיתי ברגע שהיום עצמו מתקדם, בלי ששום דבר בקוד השתנה.
 */

const { test, describe } = require('node:test');
const assert = require('node:assert');
const { appSource } = require('./_harness/sandbox.js');

describe('חיץ אמיתי לפני המעבר לתשלום', () => {
  test('נשארו יותר מ-7 ימים מהיום ועד PAY_FROM', () => {
    const app = appSource();
    const m = app.match(/const PAY_FROM='(\d{4}-\d{2}-\d{2})'/);
    assert.ok(m, 'PAY_FROM לא נמצא בקוד -- אי אפשר לבדוק את החיץ');

    /* אותו חישוב בדיוק כמו renderPayCountdown: השוואת תאריכים (setHours 0),
       לא רגעים, כדי לא לתלות את התוצאה בשעה שבה הבדיקה רצה. */
    const end = new Date(m[1] + 'T00:00:00');
    const now = new Date();
    now.setHours(0, 0, 0, 0);
    const days = Math.round((end - now) / 864e5);

    assert.ok(days > 7,
      `רק ${days} ימים נשארו עד PAY_FROM (${m[1]}) -- הבאנר יבטיח מעבר לתשלום שמערכת הגבייה אינה ערוכה לו`);
  });
});
