'use strict';
/* פירוש שנחתך לשבר משפט · ומילה שלעולם לא תיחשב נלמדה.
 *
 * הממצא (א9, 6.8.2026)
 * ---------------------
 * meaningSegs מפצל את הפירוש על פסיק. משפט אחד שיש בתוכו ", ו..." נחתך לשניים,
 * והמקטע השני אינו פירוש אלא שבר:
 *
 *   פוֹרְס מָז'וֹר  "נסיבות בלתי צפויות שאין שליטה עליהן, ועשויות לפטור מקיום התחייבות"
 *                 → ["נסיבות בלתי צפויות שאין שליטה עליהן", "ועשויות לפטור מקיום התחייבות"]
 *
 * senseCount מחזיר 2, ולכן sensesLeft דורש שני פירושים. את השני אי אפשר לתת: איש
 * אינו מקליד "ועשויות לפטור מקיום התחייבות" בתשובה למילה. commitSession חוסמת את
 * הרמה על 2 כל עוד sensesLeft>0, ו-weakCards הוא lvl<3 · כלומר המילה נעולה לנצח
 * ברשימת החיזוק. חמש מילים היו במצב הזה.
 *
 * למה זו אינה בדיקת ניסוח
 * ------------------------
 * לא נשפט כאן איזה ניסוח יפה יותר. נשפט רק האם המקטע הוא תשובה שאפשר לתת. זו
 * תקלה נמדדת ולא שאלת טעם, ולכן היא ניתנת לבדיקה.
 *
 * למה רשימת היתר ולא ביטוי רגולרי
 * ---------------------------------
 * אין ביטוי שמבחין בין וי"ו חיבור לוי"ו שורשית: "ועשויות" הוא שבר, "ויכוח" הוא
 * מילה. הסריקה מציעה מועמדים, ההכרעה בעין, והתוצאה מקובעת כאן. מקטע חדש שייפתח
 * בוי"ו יפיל את הבדיקה ויחייב הכרעה · וזה בדיוק התפקיד שלה.
 */

const { test, describe } = require('node:test');
const assert = require('node:assert');
const { loadApp } = require('./_harness/sandbox.js');

/* המקטעים היחידים שנפתחים בוי"ו ואינם שבר. כל אחד נבדק בעין. */
const ALLOWED = new Set([
  'ויכוח סוער',   // צִחְצוּחַ חַרָבוֹת · הוי"ו שורשית, "יכוח" אינה מילה
]);

function vavSegments(ctx, lang) {
  ctx.LANG = lang;
  ctx.buildBank();
  const hits = [];
  for (const w of ctx.BANK) {
    const segs = ctx.meaningSegs(w.meaning);
    if (segs.length < 2) continue;            // פירוש אחד · sensesLeft מחזיר 0 ואין דרישה
    /* meaningSegs מנרמל (מוריד ניקוד וסופיות), ולכן ההשוואה לרשימת ההיתר נעשית על
       המקטעים הגולמיים · אלה שהלומד רואה ואמור להקליד. */
    ctx.meaningSegsRaw(w.meaning).forEach(s => {
      const t = String(s).trim();
      if (/^ו/.test(t) && t.split(/\s+/).length >= 2 && !ALLOWED.has(t))
        hits.push({ term: w.term, unit: w.unit, seg: t, n: segs.length });
    });
  }
  return hits;
}

describe('פירוש שנחתך לשבר משפט', () => {

  for (const lang of ['he', 'en']) {
    test(`אין מקטע שנפתח בוי"ו ואינו תשובה אפשרית · ${lang}`, () => {
      const ctx = loadApp();
      const hits = vavSegments(ctx, lang);
      assert.deepStrictEqual(hits, [],
        `${hits.length} מקטעים נפתחים בוי"ו. כל אחד הוא או שבר משפט -- ואז המילה דורשת\n` +
        'פירוש שאי אפשר לתת ונעולה ברשימת החיזוק -- או וי"ו שורשית, ואז מקומו ב-ALLOWED:\n  ' +
        hits.map(h => `${h.term} (יח' ${h.unit}, ${h.n} מקטעים): "${h.seg}"`).join('\n  '));
    });
  }

  test('המילים שהיו נעולות אינן דורשות עוד פירוש בלתי אפשרי', () => {
    /* ההוכחה שהתיקון אכן שינה משהו, ולא רק ניסח מחדש.
       ⚠ הניסוח הראשון של הבדיקה כתב "טרוט עיניים" ביו"ד כפולה, ו-K הפיק מפתח שאינו
       קיים במאגר ("טרוט עיניימ"). הבדיקה נפלה על איות שלה, לא על הנתונים. */
    const ctx = loadApp();
    ctx.LANG = 'he'; ctx.buildBank();
    /* ארבע מהן ירדו לפירוש אחד · sensesLeft מחזיר 0 והתקרה ב-commitSession אינה חלה. */
    for (const term of ['קלח', 'טרוט עינים', 'פורס מזור', 'אתנן']) {
      const w = ctx.BANK.find(x => ctx.K(x.term) === ctx.K(term));
      assert.ok(w, `${term} נעלמה מהמאגר`);
      assert.strictEqual(ctx.sensesLeft(w.term, w.meaning), 0,
        `${w.term} עדיין דורשת פירוש נוסף -- "${ctx.meaningSegsRaw(w.meaning).join(' | ')}"`);
    }
    /* תִּכְתּוֹבֶת היא המקרה היחיד שנשאר בשני פירושים, ובכוונה: אלה שני פירושים
       אמיתיים · חילופי ההודעות, ואוסף ההודעות. הסרת הפסיק לבדה לא הספיקה לה, כי
       "בין אנשים, ארגונים או מוסדות" הוא פסיק *נוסף* בתוך אותו פירוש. הדרישה כאן
       היא ששני המקטעים יהיו תשובות שאפשר לתת. */
    const tk = ctx.BANK.find(x => ctx.K(x.term) === ctx.K('תכתובת'));
    const segs = ctx.meaningSegsRaw(tk.meaning);
    assert.strictEqual(segs.length, 2, `תכתובת: ${segs.length} מקטעים -- "${segs.join(' | ')}"`);
    segs.forEach(s => assert.ok(!/^ו/.test(s.trim()) && s.trim().split(/\s+/).length <= 7,
      `מקטע שאינו תשובה אפשרית: "${s}"`));
  });
});
