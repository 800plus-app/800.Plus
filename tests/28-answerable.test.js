'use strict';
/* כל מילה במאגר חייבת להיות מילה שאפשר לענות עליה.
 *
 * מה נמצא
 * -------
 * שלושה ערכים בעברית נשאו הערת עריכה במקום פירוש. הקיצוני שבהם:
 *
 *     ["חָרָךְ", "(לפצל לשני ערכים)"]
 *
 * meaningSegs מסירה סוגריים ואז מפצלת, ולכן הערך הזה החזיר מערך ריק — כלומר **שום
 * מחרוזת בעולם לא התקבלה כתשובה נכונה**. הכרטיס עלה בסבבים, נכשל תמיד, וחזר שוב ושוב
 * דווקא משום שנכשל.
 *
 * שניים אחרים ("בָּזַק", "בַּר") נראו תמימים יותר: היה בהם תוכן, אבל הוא הופרד ב-`·`,
 * ו-meaningSegs מפצלת על `, ; / |` ועל " - " בלבד. התוצאה הייתה קטעים כמו
 * "זרה · בזק מהירות רבה" — מחרוזות שאיש לא יקליד לעולם.
 *
 * למה זה לא נתפס עד היום
 * -----------------------
 * כל בדיקות המאגר הקיימות שואלות "האם הפירוש נכון" — כלומר האם התוכן טוב. אף אחת לא
 * שאלה את השאלה שלפניה: **האם המנגנון בכלל מסוגל לקבל תשובה כאן.** מילה כזאת אינה
 * נראית כתקלה אלא כמילה קשה, ולכן היא לא מדווחת אף פעם.
 *
 * הבדיקה רצה על שני המאגרים במלואם — 5,617 ערכים — ואינה עולה כסף.
 */

const { test, describe } = require('node:test');
const assert = require('node:assert');
const { loadApp, banks, expectNone } = require('./_harness/sandbox.js');

const he = loadApp({ lang: 'he', bank: false });
const en = loadApp({ lang: 'en', bank: false });
const b = banks();

function entries(data) {
  const out = [];
  for (const u of Object.keys(data || {}))
    for (const p of (data[u] || []))
      if (Array.isArray(p) && p.length >= 2) out.push({ unit: u, term: p[0], meaning: p[1] });
  return out;
}

const HE = entries(b.he), EN = entries(b.en);

describe('כל ערך במאגר ניתן למענה', () => {

  test('העברית — 1,717 ערכים, ולכל אחד לפחות פירוש אחד שאפשר להקליד', () => {
    const dead = HE.filter(e => he.meaningSegs(e.meaning).length === 0)
                   .map(e => `יחידה ${e.unit} · ${e.term} → "${e.meaning}"`);
    expectNone(assert, dead,
      'ערכים שאף תשובה אינה מתקבלת בהם — הכרטיס נכשל תמיד וחוזר דווקא בגלל זה:');
  });

  test('האנגלית — אותו כלל', () => {
    const dead = EN.filter(e => en.meaningSegs(e.meaning).length === 0)
                   .map(e => `unit ${e.unit} · ${e.term} → "${e.meaning}"`);
    expectNone(assert, dead, 'ערכים באנגלית שאף תשובה אינה מתקבלת בהם:');
  });

  test('אין הערות עריכה שנשלחו לאוויר כפירוש', () => {
    /* "לפצל לשני ערכים" הוא פתק שהמחבר כתב לעצמו, והוא הוצג ללומדים כהגדרה.
       הדפוס הזה חוזר — ולכן הוא נבדק ולא רק מתוקן. */
    /* התבנית מצומצמת בכוונה, ועל בשרי: הניסוח הראשון היה /לפצל|להשלים|לבדוק/ והוא סימן
       שישה תרגומים תקינים לגמרי — "check → לבדוק", "accomplish → להשלים". בדיקה שצועקת על
       נתונים תקינים מלמדת להתעלם ממנה, וזה גרוע מאין בדיקה.
       מה שמזהה הערת עריכה אינו הפועל אלא מושא הפועל: היא מדברת על **הערך עצמו** —
       "לפצל לשני ערכים", "לפצל לפי ניקוד" — ולא על מה שהמילה אומרת. */
    const marks = /לפצל[^,;]{0,20}(ערכים|ערך|ניקוד)|TODO|FIXME|\?\?\?/;
    const bad = [...HE, ...EN].filter(e => marks.test(e.meaning))
                              .map(e => `${e.term} → "${e.meaning.slice(0, 60)}"`);
    expectNone(assert, bad, 'הערות עריכה שמוצגות ללומד כפירוש:');
  });

  test('אין פירוש שכל הפרדתו היא `·` — מפריד שהמנגנון אינו מכיר', () => {
    /* `·` תקין בממשק ואינו תקין בתוך פירוש: meaningSegs לא מפצלת עליו, ולכן פירוש
       שנשען עליו נבלע לקטע אחד ארוך שאיש לא יקליד. הבדיקה תופסת את החזרה של הדפוס,
       לא רק את שלושת המקרים שכבר תוקנו. */
    const bad = [...HE, ...EN]
      .filter(e => e.meaning.includes('·') && he.meaningSegs(e.meaning).length < 2)
      .map(e => `${e.term} → "${e.meaning.slice(0, 70)}"`);
    expectNone(assert, bad,
      'פירושים שמופרדים ב-`·` בלבד — המנגנון רואה אותם כפירוש אחד ארוך:');
  });

  test('הבדיקה באמת בודקת — ערך פגום מומצא נתפס', () => {
    /* בלי זה כל האמור למעלה יכול לעבור בירוק על מאגר ריק או על meaningSegs שבורה. */
    assert.strictEqual(he.meaningSegs('(לפצל לשני ערכים)').length, 0,
      'הפירוש שהיה שבור בפועל אינו מזוהה עוד כשבור — meaningSegs השתנתה');
    assert.ok(he.meaningSegs('סדק צר, פתח צר').length >= 2,
      'פירוש תקין מזוהה כשבור');
    assert.ok(HE.length > 1700 && EN.length > 3800,
      `המאגרים לא נטענו: ${HE.length} / ${EN.length}`);
  });
});
