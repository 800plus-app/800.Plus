'use strict';
/* תחילית אחת אינה פירוש אחר.
 *
 * מה חגי ביקש (6.8.2026, קובץ המשימות)
 * --------------------------------------
 * "תפטור ה״א הידיעה, תמדוד מה אותיות קישור ומילות קישור עושות, ואם זה בטוח תעשה את זה
 * — זה יביא הכי הרבה תועלת לדעתי."
 *
 * המדידה שקבעה את הניסוח
 * ------------------------
 * נמדדו ארבע גרסאות על 24 המקרים האמיתיים שחגי צילם ועל כל 1,717 המילים בעברית:
 *
 *   גזירה גורפת של ה׳ בלבד        → תופס 1 (בלן)
 *   גזירה גורפת של ה + ב/ל/כ/מ/ש  → תופס 1 (נדן) **ושובר את בלן**
 *   השוואה סובלנית ל-ה׳ בלבד      → תופס 1 (בלן)
 *   השוואה סובלנית ל-ה/ל/ב/כ/ו    → תופס 2, אפס נזק   ← נבחר
 *
 * **הממצא שקבע:** גזירה גורפת הופכת "מרחץ" ל"רחץ" — מ׳ היא אות שורש כאן ולא תחילית —
 * ולכן היא שוברת בדיוק את ההתאמה שהיא באה לאפשר. השוואה סובלנית נוגעת רק בזוג המילים
 * שנבדק ואינה מייצרת אף גזע חדש. זה ההבדל בין השתיים, והוא כל הסיבה לניסוח.
 *
 * הנזק שנמדד, ולמה הוא אפס
 * --------------------------
 * · אפס מיזוגים בין שני פירושים של אותו כרטיס — כלומר מילה רב-משמעית לא מאבדת פירוש.
 * · 10 זוגות פירושים בכל המאגר הופכים לניתנים להחלפה, וכולם, בשמם:
 *   "שקט"/"בשקט" (×4) · "החריף"/"חריף" (×2) · "הקצין"/"קצין" · "מראה"/"המראה" ·
 *   "מקום אכסון למסמכים"/"מקום לאכסון מסמכים" (×2). **אפס קבלות שגויות.**
 *
 * להשוואה: הכלל המורפולוגי שנשקל ונדחה קיפל 61.7% מאוצר המילים ל-869 גזעים מתנגשים
 * ו-918 זוגות פירושים. דוחות/מדידת-כלל-מורפולוגי.md.
 */

const { test, describe } = require('node:test');
const assert = require('node:assert');
const { loadApp, appSource } = require('./_harness/sandbox.js');

const app = appSource();
const ctx = loadApp({ lang: 'he' });
const M = (typed, meaning) => ctx.meaningMatch(typed, meaning);

describe('particleMatch — סובלנות לתחילית אחת', () => {

  test('שני המקרים האמיתיים מהצילומים מתקבלים', () => {
    assert.ok(M('עובד בבית מרחץ', 'עובד בבית המרחץ'), 'בַּלָּן — ה״א הידיעה');
    assert.ok(M('נרתיק לחרב', 'נרתיק החרב'), 'נָדָן — ל׳ היחס מול ה״א הידיעה');
  });

  test('מילת יחס עצמאית אינה משנה את התשובה', () => {
    assert.ok(M('נרתיק של חרב', 'נרתיק החרב'), '"של" נזרק משני הצדדים');
  });

  test('אות שורש אינה נגזרת — זה מה שגזירה גורפת שברה', () => {
    /* אם מישהו יחליף את ההשוואה הסובלנית בגזירה, "מרחץ" ייחתך ל"רחץ" והבדיקה
       הראשונה כאן תיפול. זה הרגרסיה שהכי סביר שתקרה. */
    assert.ok(M('עובד בבית מרחץ', 'עובד בבית המרחץ'));
    assert.ok(!M('עובד בבית רחץ', 'עובד בבית המרחץ'),
      '"רחץ" התקבל במקום "מרחץ" — הגזירה חזרה');
  });

  test('מילה קצרה אינה תחילית ועוד אות', () => {
    /* הסף length>3 מגן על "לב", "כן", "בו". בלעדיו "לב" היה מתאים ל-"ב". */
    assert.ok(!M('לב', 'ב'), '"לב" נקלף ל-"ב"');
    assert.ok(!M('כן', 'ן'));
  });

  test('כמות מילים שונה נדחית', () => {
    /* זה מה שמונע מתשובה חלקית לעבור. "הגזים" אינו "הגזים והרחיב". */
    assert.ok(!M('נרתיק', 'נרתיק החרב'), 'תשובה חלקית התקבלה');
    assert.ok(!M('נרתיק החרב הארוך', 'נרתיק החרב'));
  });

  test('מילה שונה לגמרי עדיין נדחית', () => {
    assert.ok(!M('נרתיק לאקדח', 'נרתיק החרב'), 'מילת תוכן שונה התקבלה');
    /* ⚠ הטענה השנייה עברה מ-meaningMatch אל particleMatch עצמו, וזה שינוי אמיתי
       ולא ריכוך: "ערוך"/"מסודר" היא אחת מ-55 קבוצות הנרדפות שעברו את שער
       אפס-ההתנגשויות (typo-lab/out/synonym-gate.md), ולכן meaningMatch כן מקבל
       אותה מאז. מה שהבדיקה הזאת שומרת עליו נשאר במלואו: particleMatch הוא כלל
       תחיליות בלבד, ואסור לו לגלוש לנרדפות. */
    assert.ok(!ctx.particleMatch(ctx.norm('מסודר בערימה'), ctx.norm('ערוך בערימה')),
      'particleMatch גלש לנרדפות');
    assert.ok(M('מסודר בערימה', 'ערוך בערימה'), 'מחלקה E כבויה או שהקבוצה נעלמה');
  });

  test('אפס מיזוגים בין שני פירושים של אותו כרטיס — על כל המאגר', () => {
    /* הבדיקה הנושאת את המשקל. אם מיזוג כזה יופיע, מילה רב-משמעית תאבד פירוש:
       הלומד ייתן פירוש אחד ויזוכה גם בשני, והתקרה תיפתח בלי שהוא ידע את שניהם. */
    const bad = [];
    for (const w of ctx.BANK) {
      const parts = ctx.meaningSegs(w.meaning);
      if (parts.length < 2) continue;
      for (let i = 0; i < parts.length; i++)
        for (let j = i + 1; j < parts.length; j++)
          if (ctx.particleMatch(parts[i], parts[j])) bad.push(`${w.term} :: ${w.meaning}`);
    }
    assert.strictEqual(bad.length, 0,
      `${bad.length} כרטיסים שני פירושים שלהם התמזגו:\n  ${bad.slice(0, 5).join('\n  ')}`);
  });

  test('מה שמתקבל כנכון גם מזוכה כפירוש', () => {
    /* בלי זה נוצר הבאג של tests/62 מהכיוון השני: התשובה נכונה, אף פירוש לא מזוכה,
       sensesLeft נשאר גדול מאפס, והמילה נשארת ברשימת החיזוק לנצח. */
    const at = app.indexOf('function noteSense');
    const src = app.slice(at, at + 900);
    assert.match(src, /i=segs\.findIndex\(s=>particleMatch\(a, s\)\)/,
      'noteSense אינו נופל חזרה על particleMatch — תשובה שתתקבל לא תזוכה');
  });

  test('הסובלנות רצה אחרי ההתאמה המדויקת ולא לפניה', () => {
    /* התאמה מדויקת חייבת להישאר המסלול הראשון — היא זולה, והיא הרוב המוחלט. */
    const at = app.indexOf('function meaningMatch');
    const body = app.slice(at, app.indexOf('const PARTICLE_STOP'));
    const exact = body.indexOf('segs.includes(a)');
    const tol = body.indexOf('particleMatch');
    assert.ok(exact > 0 && tol > exact, 'הסובלנות הוקדמה לפני ההתאמה המדויקת');
  });
});
