'use strict';
/* תכונה שקיימת ואי אפשר לראות אותה אינה קיימת.
 *
 * הראיה
 * ------
 * משתמשת שתרגלה שבועות דיווחה שלא ידעה שיש התראות באפליקציה. התכונה עבדה. הכפתור
 * שמפעיל אותה היה מוסתר מאחורי `streakInfo().total>=2` — כלומר הוא הופיע רק אחרי יומיים
 * של תרגול, ובדיוק בימים שבהם אדם מחליט אם להישאר הוא לא היה שם.
 *
 * ההבחנה שהתיקון עומד עליה
 * -------------------------
 * שני דברים נראים דומים ואינם:
 *   · ה-CTA הוא כפתור באפליקציה. הוא אינו פונה לדפדפן — הלחיצה עליו פונה. אין סיכון
 *     בהצגתו למי שנכנס היום.
 *   · הדיאלוג שואל ביוזמתו, ותשובה שלילית בדפדפן היא לצמיתות ואי אפשר לבטל אותה מהקוד.
 *     הוא חייב להישאר מאחורי יומיים.
 *
 * למה בדיקת מקור ולא בדיקת דפדפן
 * -------------------------------
 * שתי השורות יושבות בתוך setTimeout בתוך פונקציית התחברות שנוגעת ב-DOM, ולכן אינן
 * ניתנות להרמה לארגז החול. חשוב מזה: בדפדפן אמיתי `Notification.permission` הוא לרוב
 * 'denied' או 'granted', ואז askable() מחזירה false ושתי השורות אינן רצות בכלל — כלומר
 * בדיקה חיה הייתה עוברת בירוק גם אם התנאי היה חוזר. כאן היא לא תעבור.
 */

const { test, describe } = require('node:test');
const assert = require('node:assert');
const { appSource } = require('./_harness/sandbox.js');

const app = appSource();

/* השורה שמסירה את ה-hidden מ-#notifCta, על כל מה שקדם לה באותה שורה. */
function ctaLine() {
  const line = app.split('\n').find(l => l.includes("$('#notifCta').classList.remove('hidden')"));
  assert.ok(line, "לא נמצאה השורה שמציגה את #notifCta — שונה שם המזהה או הוסרה ההצגה");
  return line;
}

function dialogBlock() {
  const at = app.indexOf("show($('#notifAsk'))");
  assert.ok(at > 0, 'לא נמצאה ההצגה של דיאלוג ההתראות');
  return app.slice(Math.max(0, at - 400), at);
}

describe('כפתור ההתראות נראה מהיום הראשון', () => {

  test('ה-CTA אינו מותנה ברצף תרגול', () => {
    const line = ctaLine();
    assert.ok(!/streakInfo\(\)/.test(line),
      'ה-CTA חזר להיות מותנה ב-streakInfo — זה בדיוק מה שהסתיר אותו:\n  ' + line.trim());
  });

  test('ה-CTA עדיין מותנה ב-askable — לא מוצג למי שאסור לשאול', () => {
    /* iOS בלשונית Safari זורק כשנוגעים ב-Notification, ומי שכבר ענה "לא" ענה לצמיתות.
       הסרת התנאי הזה הייתה הופכת את התיקון לתקלה. */
    const line = ctaLine();
    assert.ok(/NOTIF\.askable\(\)/.test(line),
      'ה-CTA מוצג בלי askable() — יוצג למי שכבר סירב, ועל iOS בדפדפן זה גם זורק');
  });

  test('הדיאלוג היזום נשאר מאחורי יומיים', () => {
    /* התנאי הזה אינו זהירות יתר: הדיאלוג שואל את הדפדפן ביוזמתו, ו"לא" בדפדפן הוא
       סופי. הוא חייב להישאר מותנה — אחרת התיקון של הנראות הורס את מה שהוא בא לשפר. */
    const block = dialogBlock();
    assert.ok(/streakInfo\(\)\.total\s*>=\s*2/.test(block),
      'הדיאלוג היזום כבר אינו מותנה ביומיים — שאלה לזר נענית "לא" והתשובה לצמיתות');
    assert.ok(/hw_notifOffered/.test(block),
      'הדיאלוג אינו מוגן מהצגה חוזרת');
  });

  test('שניהם אינם אותה שורה', () => {
    /* אם מישהו יאחד אותם בעתיד, אחד מהשניים ייסוג לתנאי של האחר, ושתי הבדיקות שלמעלה
       ימשיכו לעבור בזמן שההתנהגות נשברת. */
    assert.ok(!ctaLine().includes("show($('#notifAsk'))"),
      'ה-CTA והדיאלוג אוחדו לשורה אחת — התנאים השונים הם כל העניין');
  });
});
