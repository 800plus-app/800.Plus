const { test, describe } = require('node:test');
const assert = require('node:assert');
const { loadApp, appSource } = require('./_harness/sandbox.js');

const app = appSource();

/* מילה אמיתית מהמאגר עם שני פירושים ומעלה · התקרה חלה רק עליהן. */
function multiSenseWord(ctx) {
  for (const w of ctx.uniqScope('unit:1')) {
    if (ctx.senseCount(w.meaning) >= 2) return w;
  }
  throw new Error('אין ביחידה 1 מילה עם שני פירושים — הבדיקה איבדה את הנחת היסוד שלה');
}

/* מריץ סבב אחד שבו הלומד טעה ואז הצהיר שידע, ומחזיר את הרמה שנרשמה. */
function levelAfterDeclare(ctx, { declared }) {
  const w = { ...multiSenseWord(ctx), _dir: 'w2m' };
  const r = ctx.rec(w.term);
  r.seen = 3; r.level = 2;                    // מילה מוכרת שכבר תורגלה, לא חדשה
  ctx.stats.words[ctx.K(w.term)].sens = [];   // אף פירוש לא זוכה · בדיוק המצב בדיווח
  /* attempts=1 · mastered · firstTry · בדיוק מה שה-handler של #wasRight קובע אחרי טעות. */
  const e = { w, attempts: 1, mastered: true, firstTry: true };
  if (declared) e.declared = true;
  ctx.session.set(ctx.K(w.term), e);
  ctx.commitSession();
  return ctx.rec(w.term).level;
}

describe('"בעצם צדקתי" · הצהרת ידיעה מרימה את תקרת הפירושים', () => {

  test('אחרי הלחיצה המילה מגיעה לרמה 3 ויוצאת מרשימת החיזוק', () => {
    /* בלי התיקון: 2. weakCards דורש 3, ולכן המילה חוזרת לתרגול לנצח · הדיווח עצמו. */
    const ctx = loadApp({ lang: 'he' });
    assert.strictEqual(levelAfterDeclare(ctx, { declared: true }), 3,
      'הצהרת ידיעה מפורשת עדיין נעצרת בתקרת הפירושים — המילה תישאר "חלשה" אחרי הלחיצה');
  });

  /* ⚠ התהפכה ב-7.8.2026, בהכרעת חגי. הפירוט המלא ב-tests/35.
     בקצרה: התקרה חלה על 64.5% מהמאגר ולא על מקרה קצה, ולכן רוב המילים נתקעו
     ברמה 2. **בוטלה החובה, לא המידע** · הפירושים הנוספים עדיין מוצגים. */
  test('אין תקרה גם בלי הצהרה · פירוש אחד מספיק', () => {
    const ctx = loadApp({ lang: 'he' });
    assert.strictEqual(levelAfterDeclare(ctx, { declared: false }), 3,
      'התקרה חזרה — מילה רב-משמעית נעצרת ברמה 2 וחוזרת לחיזוק בלי סוף');
  });

  test('הדגל נקבע ב-#wasRight ונוקה בביטול', () => {
    /* ה-handler יושב בתוך finishCard ואינו ניתן להרמה לארגז החול, ולכן נבדק במקור.
       הביטול הוא החצי שקל לשכוח: בלעדיו לחיצה בטעות מותירה מילה שמטפסת ל-3. */
    const at = app.indexOf("wr.onclick=()=>{");
    assert.ok(at > 0, 'ה-handler של "בעצם ידעתי" נעלם');
    const body = app.slice(at, at + 1400);
    assert.match(body, /e\.declared=true/,
      'הלחיצה אינה מסמנת הצהרת ידיעה — התקרה תמשיך לכלוא את המילה');
    assert.match(body, /e\.declared=false/,
      'הביטול אינו מנקה את הדגל — מילה תטפס ל-3 על סמך לחיצה שבוטלה');
  });

  test('commitSession אינו מחזיק עוד שורת תקרה', () => {
    /* ⚠ הבדיקה הפוכה מקודמתה (7.8.2026). `const cap =` היה הביטוי של התקרה,
       והוא הוסר. אם הוא חוזר · מישהו החזיר את החסימה שחגי ביקש להסיר. */
    assert.ok(app.indexOf('const cap =') < 0,
      'שורת התקרה חזרה ל-commitSession — רוב המאגר ייתקע שוב ברמה 2');
  });

  test('גם התיקון ממסך הסיכום מרים את התקרה', () => {
    /* .rev-chip הוא הדלת השנייה לאותה הצהרה. בלי הדגל כאן, מי שמתקן מהסיכום · וזה
       המסלול שד4 עצמה הפנתה אליו · היה מקבל את אותו באג בדיוק דרך שער אחר. */
    const at = app.indexOf("chip.onclick=()=>{");
    assert.ok(at > 0, 'ה-handler של .rev-chip נעלם');
    const body = app.slice(at, at + 700);
    assert.match(body, /e\.declared=nowOk/,
      'התיקון ממסך הסיכום אינו מסמן הצהרה — המילה תישאר "חלשה"');
  });

  test('creditSense לא נגעה · ההחלטה של tests/35 עומדת', () => {
    /* התיקון הזה נבחר במפורש כדי לא להרפות את הזיכוי. אם מישהו בכל זאת יוסיף שלב שלישי,
       הבדיקה הזאת תזכיר שזה נמדד פעם והוחזר. */
    const at = app.indexOf('function creditSense');
    /* החלון חייב להגיע עד סוף הפונקציה. 900 תווים נעצרו באמצע ההערה הארוכה שבתוכה,
       והבדיקה נפלה על קוד תקין · מתקנים את הבדיקה, לא את הקוד. */
    const src = app.slice(at, at + 1800);
    assert.match(src, /if\(i<0\) return;/,
      'creditSense מזכה גם בלי התאמה — הבאג שתועד ב-tests/35 חזר');
  });
});
