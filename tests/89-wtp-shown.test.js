'use strict';
/* סקר התשלום · הדגל «כבר נשאל» נדלק רק כשהכרטיס באמת הוצג.
 *
 * מה שהיה
 * -------
 * `maybeAskWtp` הדליקה `wtpShown = true` **לפני** ה-`setTimeout`, וההצגה בפועל
 * (`show($('#wtpAsk'))`) יושבת בסופו. בין השניים שלוש יציאות מוקדמות:
 *
 *   1. מסך התוצאות כבר נעזב כשהטיימר ירה (שתי שניות · די והותר ללחוץ «חזרה»)
 *   2. `Store.wtpAsked()` החזירה true · כולל הנפילה-סגורה שלה על כל שגיאה
 *   3. מסך התוצאות נעזב בזמן ההמתנה לשרת
 *
 * בכל אחת מהן הלומד נספר כמי שנשאל בזמן שלא ראה כלום, והסקר אינו חוזר עד
 * טעינת עמוד חדשה. ‏16 לומדים בלבד ראו את הכרטיס.
 *
 * ⚠ **מה שהדגל אינו** · הוא מקומי לטעינת עמוד. הרישום העמיד הוא שורה בטבלה,
 * ו-`Store.wtpAsked()` היא שקוראת אותה. כלומר האובדן הוא בתוך אותה טעינה,
 * לא «לעולם». נאמר כאן כפי שנמדד ולא כפי שנוסח במשימה.
 *
 * למה שער טקסטואלי ולא הרצה
 * -------------------------
 * `maybeAskWtp` נוגעת ב-`document`, ב-`setTimeout` וב-`Store` ואינה ניתנת
 * להרמה לסנדבוקס. לכן הסדר נבדק על מקור הקובץ, והמשמעות נבדקת על מודל · אותה
 * חלוקה בדיוק שב-`tests/38-commit-flag`.
 *
 * ⛔ ההערות יורדות לפני הבדיקה. שער שמחפש **שם** ולא **קוד** עובר על הערה
 * שמזכירה את השם · כך `k0` חמק בזמנו, וכך `tests/39` נמצא עיוור.
 */

const { test, describe } = require('node:test');
const assert = require('node:assert');
const { appSource } = require('./_harness/sandbox.js');
const { codeMask, matchBrace, codeMatches } = require('./_harness/scan.js');

/** גוף `maybeAskWtp` כפי שהוא במקור, כולל הסוגריים המסולסלים. */
function גוףהפונקציה(src) {
  const at = src.indexOf('function maybeAskWtp');
  assert.notStrictEqual(at, -1,
    'הפונקציה maybeAskWtp אינה בקובץ · שונתה או נמחקה, והשער הזה מפסיק להגן');
  const mask = codeMask(src);
  const open = src.indexOf('{', at);
  const close = matchBrace(src, open, mask);
  assert.ok(close > open, 'חילוץ maybeAskWtp נכשל · הסוגר לא נמצא');
  return { טקסט: src.slice(at, close + 1), מ: at };
}

/** מיקומי כל מופע של `re` בגוף, בקוד בלבד · הערות ומחרוזות אינן נספרות. */
function מיקומים(גוף, re) {
  return codeMatches(גוף, re, codeMask(גוף)).map(m => m.at);
}

/* ── הסדר במקור ─────────────────────────────────────────────────── */
describe('הדגל נדלק רק אחרי ההצגה', () => {

  test('wtpShown = true יושב אחרי show($(#wtpAsk))', () => {
    const { טקסט } = גוףהפונקציה(appSource());
    const הדלקות = מיקומים(טקסט, /wtpShown\s*=\s*true/);
    const הצגות = מיקומים(טקסט, /show\(\s*\$\(\s*['"]#wtpAsk['"]\s*\)\s*\)/);

    assert.strictEqual(הצגות.length, 1,
      `ציפיתי להצגה אחת של #wtpAsk בתוך maybeAskWtp, נמצאו ${הצגות.length}`);
    assert.strictEqual(הדלקות.length, 1,
      `ציפיתי להדלקה אחת של wtpShown בתוך maybeAskWtp, נמצאו ${הדלקות.length}`);
    assert.ok(הדלקות[0] > הצגות[0],
      'wtpShown נדלק לפני ההצגה · לומד שיצא ממסך התוצאות בתוך שתי שניות ' +
      'נספר כמי שנשאל ולא יראה את הסקר עד טעינת עמוד חדשה');
  });

  test('ההדלקה יושבת בתוך ה-setTimeout ולא לפניו', () => {
    const { טקסט } = גוףהפונקציה(appSource());
    const טיימר = מיקומים(טקסט, /setTimeout\s*\(/);
    assert.strictEqual(טיימר.length, 1, 'ציפיתי ל-setTimeout אחד בתוך maybeAskWtp');
    const הדלקה = מיקומים(טקסט, /wtpShown\s*=\s*true/)[0];
    assert.ok(הדלקה > טיימר[0],
      'wtpShown נדלק לפני ה-setTimeout · ההצגה עוד לא קרתה ואולי לא תקרה');
  });

  /* ⭐ הבדיקה הזאת היא מה שמונע «תיקון» שמסיר את השמירה לגמרי. בלי מחסום
     כלשהו, שני סבבים שנסגרו בתוך שתי שניות זה מזה מציגים את הכרטיס פעמיים. */
  test('נשאר מחסום מפני הצגה כפולה · לפני ההצגה ואחרי ההמתנה לשרת', () => {
    const { טקסט } = גוףהפונקציה(appSource());
    const שומרים = מיקומים(טקסט, /if\s*\(\s*wtpShown\s*\)\s*return/);
    const הצגה = מיקומים(טקסט, /show\(\s*\$\(\s*['"]#wtpAsk['"]\s*\)\s*\)/)[0];
    const אחרי = מיקומים(טקסט, /await\s+Store\.wtpAsked/)[0];
    assert.ok(שומרים.some(s => s > אחרי && s < הצגה),
      'אין בדיקת wtpShown בין קריאת השרת לבין ההצגה · שני טיימרים פתוחים ' +
      'יציגו את הכרטיס פעמיים');
  });

  /* ⛔ הכישלון הסגור באזור הוא מכוון · אסור «לתקן» אותו.
     הערה מקבילה יושבת מעל הפונקציה ב-app.js, וזה השער שמחזיק אותה. */
  test('הנפילה-הסגורה נשמרה · שגיאה לעולם לא שוברת את מסך התרגול', () => {
    const { טקסט } = גוףהפונקציה(appSource());
    /* ⛔ **סביב `Store.wtpAsked` בדיוק, לא «יש catch ריק איפשהו».**
       הניסוח הראשון היה `/catch\(e\)\{\}/` על כל גוף הפונקציה · ואז נוסף
       `try{ Store.wtpMarkShown(); }catch(e){}` באותה פונקציה, והבדיקה המשיכה
       לעבור גם כשה-catch סביב הקריאה לשרת הוסר לגמרי. נמדד: המוטציה `nocatch`
       החזירה 9/9 ירוק. שער שנעשה עיוור מעריכה שלא נגעה בו בכלל. */
    assert.ok(/try\s*\{\s*asked\s*=\s*await\s+Store\.wtpAsked\(\);\s*\}\s*catch\s*\(\s*e\s*\)\s*\{\s*\}/.test(טקסט),
      'ה-catch הריק סביב Store.wtpAsked הוסר · שגיאת רשת תשבור עכשיו את מסך התוצאות');
  });
});

/* ── המשמעות, על מודל ───────────────────────────────────────────── */
/* מימוש מקביל לשלוש היציאות המוקדמות. הפונקציה עצמה אינה ניתנת להרמה, ולכן
   ההתנהגות נבדקת כאן והשערים למעלה מוודאים שהכלל אכן כתוב ב-app.js. */
function מודל(סדרחדש) {
  return {
    shown: false, הוצג: 0, ממתינים: 0,
    סבבשנסגר() {
      if (this.shown) return;
      if (!סדרחדש) this.shown = true;           // ← הקוד הישן
      this.ממתינים++;
    },
    /* הטיימר יורה. `עלהמסך` · הלומד עדיין במסך התוצאות · `נשאלכבר` · תשובת השרת */
    טיימר({ עלהמסך = true, נשאלכבר = false } = {}) {
      /* אין טיימר פתוח · הסבב שנסגר יצא מוקדם, ולכן אין מה לירות. בלי השורה
         הזאת המודל «יורה» טיימר שמעולם לא נקבע, ומצייר את הקוד הישן כתקין. */
      if (this.ממתינים === 0) return;
      this.ממתינים--;
      if (!עלהמסך) return;
      if (נשאלכבר) return;
      if (סדרחדש && this.shown) return;
      this.הוצג++;
      if (סדרחדש) this.shown = true;            // ← התיקון
    },
  };
}

describe('מה קורה ללומד', () => {

  test('יצא ממסך התוצאות בתוך שתי שניות · הסבב הבא עדיין שואל', () => {
    const m = מודל(true);
    m.סבבשנסגר(); m.טיימר({ עלהמסך: false });   // עזב · לא ראה כלום
    m.סבבשנסגר(); m.טיימר();                    // סבב הבא · נשאר
    assert.strictEqual(m.הוצג, 1, 'הסקר לא הוצג גם בסבב השני');
  });

  test('אותו תרחיש בקוד הישן · הסקר נעלם לשארית הטעינה', () => {
    const m = מודל(false);
    m.סבבשנסגר(); m.טיימר({ עלהמסך: false });
    m.סבבשנסגר(); m.טיימר();
    assert.strictEqual(m.הוצג, 0,
      'המודל של הקוד הישן אינו משחזר את הבאג · הבדיקה שמעליו חסרת ערך');
  });

  test('קריאת השרת נכשלה ונפלה סגורה · הסבב הבא עדיין שואל', () => {
    const m = מודל(true);
    m.סבבשנסגר(); m.טיימר({ נשאלכבר: true });   // wtpAsked מחזירה true על שגיאה
    m.סבבשנסגר(); m.טיימר();
    assert.strictEqual(m.הוצג, 1, 'שגיאת רשת אחת שרפה את הסקר');
  });

  test('הוצג פעם אחת · לא חוזר שוב באותה טעינה', () => {
    const m = מודל(true);
    m.סבבשנסגר(); m.טיימר();
    m.סבבשנסגר(); m.טיימר();
    m.סבבשנסגר(); m.טיימר();
    assert.strictEqual(m.הוצג, 1, 'הכרטיס חזר · זו הטרדה, לא סקר');
  });

  test('שני סבבים נסגרו בתוך שתי שניות · הכרטיס עדיין מוצג פעם אחת', () => {
    const m = מודל(true);
    m.סבבשנסגר(); m.סבבשנסגר();                 // שני טיימרים פתוחים
    assert.strictEqual(m.ממתינים, 2, 'המודל לא ייצר שני טיימרים · התרחיש לא נבדק');
    m.טיימר(); m.טיימר();
    assert.strictEqual(m.הוצג, 1, 'הכרטיס הוצג פעמיים');
  });
});
