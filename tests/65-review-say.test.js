'use strict';
/* רמקול על המילים שנטעו, במסך סיכום הסבב.
 *
 * הבקשה (חגי, קובץ המשימות 6.8.2026, פריט א10)
 * ---------------------------------------------
 * "תוסיף אופציה של שמע למילים בסוף התרגול ככה שיהיה אפשר לשמוע את המילים שטעית בהן".
 *
 * שלוש הכרעות שכדאי שיהיו כתובות, כי כל אחת מהן נראית כמו באג למי שלא יודע אותן
 * -----------------------------------------------------------------------------
 * 1. **רק מה שנטעה.** לא כל השורות. מסך של 20 שורות עם 20 רמקולים הוא רעש, ושלוש
 *    השורות שדורשות תשומת לב נבלעות בו — בדיוק הנימוק שכבר הוליד את מיון השורות
 *    ב-renderReview.
 *
 * 2. **הרמקול נקבע ברינדור ואינו זז עם ה-chip.** לחיצה על "✓ ידעתי" משנה צבע במקום,
 *    לא מסירה כפתור מתחת לאצבע. זו אותה הכרעה שכבר מתועדת שם על סדר השורות
 *    ("הצבע משתנה במקום, המיקום נשאר"), ולא הכרעה חדשה.
 *
 * 3. **במאגר העברי אין רמקול בכלל.** TTS.pick בוחר קול אנגלי בלבד — אין בו ענף עברי
 *    ולא הוסף כאן אחד. כפתור שלא יודע להגות את מה שכתוב עליו גרוע מהעדרו, וזה בדיוק
 *    הנימוק שכבר כתוב מעל bindSay. לכן התנאי הוא LANG==='en', לא TTS.available לבדו.
 *
 * למה בדיקת מקור ולא ארגז חול
 * ----------------------------
 * renderReview כותבת innerHTML וקוראת ל-$ — היא אינה ניתנת להרמה. הכלל נבדק כאן על
 * הטקסט של app.js, ואומת בנוסף בדפדפן. ראה tests/README.md.
 */

const { test, describe } = require('node:test');
const assert = require('node:assert');
const { appSource } = require('./_harness/sandbox.js');

const app = appSource();
const review = app.slice(app.indexOf('function renderReview'),
                         app.indexOf('function commitSession'));

describe('רמקול במסך סיכום הסבב', () => {

  test('renderReview מחשבת האם בכלל אפשר להשמיע', () => {
    assert.match(review, /LANG==='en'\s*&&\s*TTS\.available\(\)/,
      'התנאי אינו LANG==="en" && TTS.available() — או שהרמקול יופיע במאגר העברי בלי קול, או שלא יופיע כלל');
  });

  test('הרמקול נתלה רק על שורה שנטעתה', () => {
    /* אם התנאי יאבד את `!ok`, כל 20 השורות יקבלו רמקול והמסך יהפוך לרעש. */
    assert.match(review, /canSay\s*&&\s*!ok/,
      'הרמקול אינו מותנה ב-!ok — הוא ייתלה גם על מילים שנענו נכון');
  });

  test('לחיצה על הרמקול משמיעה את המילה, לא את הפירוש', () => {
    /* ⚠ הניסוח הראשון היה `TTS\.say\([^)]*dataset\.t` והוא נפל על קוד תקין: הארגומנט
       הוא `btn.closest('.rev-row').dataset.t`, ו-[^)]* אינו יכול לחצות את הסוגר של
       closest. הבדיקה תוקנה, לא הקוד. */
    assert.match(review, /TTS\.say\([\s\S]{0,60}?dataset\.t/,
      'ההשמעה אינה נשענת על data-t של השורה — ייתכן שהיא משמיעה את הטקסט הלא נכון');
  });

  test('ה-chip אינו נוגע ברמקול', () => {
    /* הכרעה 2. אם הענף הזה יתחיל להוסיף או להסיר .rev-say, כפתור יזוז מתחת לאצבע. */
    const chip = review.slice(review.indexOf(".rev-chip').forEach"));
    assert.ok(!/rev-say/.test(chip),
      'המטפל של ה-chip נוגע ב-.rev-say — כפתור יופיע או ייעלם מתחת לאצבע בזמן לחיצה');
  });
});
