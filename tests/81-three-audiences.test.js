'use strict';
/* שלושה מיילים, שלושה קהלים · והגבול ביניהם חייב להישאר צמוד.
 *
 * מי שייך לאן
 * -----------
 *   pick_inactive  · לא תרגל אף מילה                → «נרשמת ולא פתחת»
 *   pick_lapsed    · תרגל, 1 עד 4 לחיזוק, שקט       → המייל השלישי
 *   pick_nudges    · 5 מילים לחיזוק ומעלה           → התזכורת השבועית
 *
 * ⛔ הסיכון האמיתי אינו שאחד מהם שגוי היום · הוא ששניים מהם יזוזו בנפרד. הסף
 * `n < 5` יושב ב-`pick_nudges` ו-`WEAK_MAX = 4` יושב ב-`pick_lapsed`, ואין שום
 * דבר שמקשר ביניהם חוץ מכך שמישהו זכר. מי שיוריד את הסף ל-3 ולא ייגע בשני יפתח
 * חור שקט של שתי מילים · או, בכיוון השני, ישלח שני מיילים לאותו אדם.
 *
 * זה בדיוק הכשל שכבר קרה כאן פעם אחת: `activation-email.yml` הצהיר «אדם אחד לא
 * יקבל את שניהם» על סמך הנחה שאיש לא בדק, וההצהרה הייתה שקרית.
 *
 * ⛔ ומה שהשער הזה **אינו** עושה: הוא אינו מריץ את הבוררים. הוא קורא מספרים
 * מהמקור. הרצה אמיתית דורשת פייתון, והחבילה הזאת היא node · הריצה על פיקסטורה
 * מתועדת ביוצא של הסשן.
 */

const { test, describe } = require('node:test');
const assert = require('node:assert');
const fs = require('fs');
const path = require('path');

const שורש = path.join(__dirname, '..');
const קרא = f => fs.readFileSync(path.join(שורש, f), 'utf8');

/** מספר יחיד מתוך התאמה · נופל ברעש אם הצורה השתנתה, ולא מחזיר undefined בשקט. */
function מספר(src, re, מה) {
  const m = src.match(re);
  assert.ok(m, `לא נמצא ${מה} · הצורה בקוד השתנתה והשער הזה עיוור מעכשיו`);
  return Number(m[1]);
}

describe('הגבול בין התזכורת למייל השלישי', () => {

  test('הסף בשני הקבצים צמוד · אין חור ואין חפיפה', () => {
    const סף = מספר(קרא('scripts/pick_nudges.py'), /if\s+n\s*<\s*(\d+)\s*:/,
      'הסף של pick_nudges');
    const מקס = מספר(קרא('scripts/pick_lapsed.py'), /WEAK_MAX\s*=\s*(\d+)/,
      'WEAK_MAX ב-pick_lapsed');
    assert.strictEqual(מקס, סף - 1,
      `‏WEAK_MAX=${מקס} מול סף התזכורת ${סף}. ` +
      (מקס < סף - 1
        ? `מי שיש לו ${מקס + 1} עד ${סף - 1} מילים לחיזוק אינו מקבל שום מייל`
        : `מי שיש לו ${סף} מילים לחיזוק יקבל שני מיילים`));
  });

  test('המייל השלישי דורש שתורגלה לפחות מילה אחת · זר למייל ההפעלה', () => {
    const s = קרא('scripts/pick_lapsed.py');
    assert.ok(/if\s+n_met\s*==\s*0\s*:[\s\S]{0,160}?skip\s*\(/.test(s),
      'pick_lapsed אינו פוסל את מי שלא תרגל כלום · הוא ייכנס גם למייל ההפעלה');
  });

  test('מייל ההפעלה פוסל את מי שכן תרגל · זר למייל השלישי', () => {
    const s = קרא('scripts/pick_inactive.py');
    assert.ok(/if\s+n_met\s*:[\s\S]{0,160}?skip\s*\(/.test(s),
      'pick_inactive אינו פוסל את מי שתרגל · שני הקהלים חופפים שוב');
  });

  /* ⛔ «שקט» חייב להימדד מהאפליקציה. `last_seen` נכתב רק כשמקלידים סיסמה, ולכן
     בורר שנשען עליו כאן היה שולח למי שתרגל אתמול. */
  test('«שקט» נמדד מתאריך התרגול ולא מתאריך הכניסה', () => {
    const s = קרא('scripts/pick_lapsed.py');
    assert.ok(/r\.get\(\s*['"]last['"]\s*\)/.test(s),
      'pick_lapsed אינו קורא את תאריך התרגול שהאפליקציה כותבת');
    assert.ok(!/p\.get\(\s*['"]last_seen['"]\s*\)/.test(s),
      'pick_lapsed נשען על last_seen · השדה הזה ריק אצל לומדים פעילים');
  });
});

describe('הנוסח של המייל השלישי', () => {

  const s = () => קרא('scripts/send_lapsed.py');

  /* ⛔ **רק שתי פונקציות הנוסח, לא הקובץ.** הכללים של `/HEB` חלים על טקסט שלומד
     קורא · לא על שורות לוג ולא על הערות. שער שסורק את הקובץ כולו נופל על ההערה
     שמתעדת מה נפסל, וזה בדיוק סוג הרעש שגורם לשער אמיתי להיות מושתק.
     ⚠ וזה קרה כאן: הגרסה הראשונה של השער הזה מצאה שמונה «מקפים ארוכים בנוסח»,
     וכולם היו בהערות ובפלט של Actions. */
  function נוסח() {
    const t = s();
    const מ = t.indexOf('def subject(');
    const עד = t.indexOf('def mask(');
    assert.ok(מ > 0 && עד > מ, 'לא נמצאו פונקציות הנוסח · השער הזה עיוור מעכשיו');
    const קטע = t.slice(מ, עד);
    /* ההערות יורדות · אחרת «מחכות לך» שכתוב כדוגמה למה שנפסל נספר כהפרה.
       זה בדיוק הכשל שכבר נמצא כאן פעמיים, ב-tests/39 וב-tests/78.

       ⛔ `[^f]` לפני הגרשיים אינו קישוט. **גוף המייל עצמו הוא f-string משולש**,
       וניסוח בלי התנאי הזה מחק אותו כולו: הקטע ירד מ-3,864 תווים ל-800, ועשר
       בדיקות הנוסח רצו על טקסט שאין בו מייל. הן היו ירוקות ועיוורות · המוטציה
       שהחליפה את שורת הפתיחה במשפט מאשים **לא נתפסה על ידן**. */
    const נקי = קטע.replace(/(^|[^f])"""[\s\S]*?"""/g, '$1 ')
      .replace(/(^|\n)\s*#[^\n]*/g, '$1')
      .replace(/<!--[\s\S]*?-->/g, ' ');
    /* ⭐ והשומר נגד אותו כשל בעתיד: אם הניקוי בלע את הגוף, זה נראה בדיוק כמו
       הצלחה. שני עוגנים שחייבים לשרוד · אחד מהנושא ואחד מגוף ה-HTML.
       ⛔ והעוגנים הם **מבנה ולא נוסח**. עוגן שהוא בעצמו טקסט נבדק (כמו טקסט
       הכפתור) היה מפיל את כל עשר הבדיקות יחד בכל שינוי ניסוח · נמדד, 14 כשלים
       ממוטציה אחת. רעש כזה הוא מה שגורם לשער אמיתי להיות מושתק. */
    assert.ok(/role="presentation"/.test(נקי), 'הניקוי בלע את גוף המייל · השער עיוור');
    assert.ok(/%d מילים לחיזוק/.test(נקי), 'הניקוי בלע את שורת הנושא · השער עיוור');
    return נקי;
  }

  /* ⛔ חגי: «כמובן לא לנסח אותו ככה». וב-1.8.2026 הוא ביטל לגמרי מייל שנשען על
     היעדר פעילות. הרשימה כאן היא בדיוק מה שנפסל, ולא ניחוש. */
  const אסור = ['לא נכנסת', 'לא חזרת', 'לא תרגלת', 'מזמן', 'חבל ש', 'מחכות לך', 'מחכה לך',
    'הזמן עובר', 'התגעגענו', 'נעלמת'];

  for (const ביטוי of אסור) {
    test(`אין «${ביטוי}» בנוסח`, () => {
      assert.ok(!נוסח().includes(ביטוי),
        `הנוסח מזכיר את השקט או מאשים · «${ביטוי}» נפסל במפורש`);
    });
  }

  test('אין מקף ארוך בנוסח', () => {
    /* אותו כלל כמו tests/75 · מקף ארוך ליד אות עברית הוא סממן AI. */
    const n = נוסח();
    const מופעים = [...n.matchAll(/—/g)].filter(m =>
      /[א-ת]/.test(n.slice(Math.max(0, m.index - 25), m.index + 25)));
    assert.strictEqual(מופעים.length, 0, `נמצאו ${מופעים.length} מקפים ארוכים ליד עברית`);
  });

  test('הכפתור הוא «תרגל עכשיו» · המונח מהלקסיקון', () => {
    assert.ok(/>תרגל עכשיו</.test(נוסח()), 'טקסט הכפתור אינו «תרגל עכשיו»');
  });

  test('יש מספר אמיתי בשורת הנושא ובגוף', () => {
    const t = נוסח();
    assert.ok(/תרגלת %d מילים · %d מהן לחיזוק/.test(t),
      'שורת הנושא בלי תאריך מבחן אינה נושאת שני מספרים');
    assert.ok(/תרגלת \{met\} מילים/.test(t), 'הגוף אינו פותח במה שהלומד עשה');
  });

  /* ⛔ «1 ימים» אינו עברית. אותו ענף כמו send_nudges, ומאותה סיבה. */
  test('עברית תקינה למספר הימים', () => {
    const t = נוסח();
    for (const צורה of ['המבחן היום', 'המבחן מחר', 'נשארו לך יומיים עד המבחן'])
      assert.ok(t.includes(צורה), `חסר הענף «${צורה}» · «1 ימים» ייצא ללומד`);
  });

  test('ריצה יבשה היא ברירת המחדל', () => {
    assert.ok(/DRY\s*=\s*os\.environ\.get\(\s*'DRY'\s*,\s*'true'\s*\)/.test(s()),
      'ברירת המחדל אינה ריצה יבשה · מייל שיצא אי אפשר לבטל');
  });
});
