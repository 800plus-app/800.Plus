'use strict';
/* עומק · שכבה אחת אינה עומק.
 *
 * מדוד לפני התיקון: 34 משטחים ב-`--card` על `--paper` ב-**1.11:1**, מופרדים
 * בקו `--line` ב-1.39:1 · זה היה כל תקציב העומק של האפליקציה מחוץ למסך
 * ההתחברות. 1.11:1 נמצא מתחת לסף שבו העין מבחינה בהפרש שטח גדול, ולכן
 * הכרטיסים נקראו כמודבקים ולא כמונחים.
 *
 * ⭐ המודל לא הומצא. מסך ההתחברות כבר החזיק אותו במלואו · כיוון אור אחד, קו
 * ספקולרי פנימי, ושקעים · והוא היה כלוא שם. שאר האפליקציה קיבלה טוקן אחד
 * (`--shadow`) ועוד 27 צללים ייחודיים בלי כיוון אור משותף, כלומר הצללים רמזו
 * על מקור אור שהרקע סתר.
 *
 * שני הכללים שהשער הזה שומר:
 *   1. הצל חם. צל אפור על שמנת נקרא כלכלוך · זה כתוב בהערה במסך ההתחברות.
 *   2. יש שקע, לא רק הרמה. שתי רמות (מורם מול שקוע) נקראות עמוק יותר משלוש
 *      רמות של מורם, וזה החצי שלא היה בשימוש בשום מקום.
 */
const { test, describe } = require('node:test');
const assert = require('node:assert');
const fs = require('fs');
const path = require('path');
const { ROOT } = require('./_harness/sandbox.js');
const html = fs.readFileSync(path.join(ROOT, 'index.html'), 'utf8');

describe('טוקני העומק קיימים ומוחלים', () => {

  test('שלושת הטוקנים מוגדרים', () => {
    for (const t of ['--lift-1', '--lift-2', '--well'])
      assert.ok(html.includes(t + ':'), `הטוקן ${t} נעלם`);
  });

  test('⛔ הצל חם · לא אפור', () => {
    /* rgba(x,x,x) עם שלושה ערכים זהים הוא אפור, והוא נקרא כלכלוך על שמנת. */
    const defs = html.match(/--(lift-1|lift-2|well):[^;]+;/g) || [];
    assert.ok(defs.length >= 3, 'הגדרות הטוקנים נעלמו');
    for (const d of defs) {
      for (const m of d.matchAll(/rgba\((\d+),\s*(\d+),\s*(\d+)/g)) {
        const [r, g, b] = [m[1], m[2], m[3]].map(Number);
        if (r === 255 && g === 255 && b === 255) continue;   // הקו הספקולרי הלבן
        assert.ok(!(r === g && g === b), `צל אפור בטוקן: ${m[0]} · על שמנת זה נקרא כלכלוך`);
        assert.ok(r > b, `הצל אינו חם (r=${r} b=${b}) · הוא חייב לנטות לחום ולא לכחול`);
      }
    }
  });

  test('⭐ יש קו ספקולרי פנימי · זה מה שהופך מלבן למשטח מואר', () => {
    for (const t of ['lift-1', 'lift-2'])
      assert.ok(html.includes('--' + t + ':inset 0 1px 0 rgba(255,255,255'),
        `--${t} איבד את הקו הלבן הפנימי`);
  });

  test('⭐ השקע בשימוש · לא רק הרמה', () => {
    const uses = (html.match(/var\(--well\)/g) || []).length;
    assert.ok(uses >= 3, `--well בשימוש ${uses} פעמים · שתי רמות נקראות עמוק יותר משלוש של מורם`);
    /* מסלולי ההתקדמות הם המקום הטבעי · הם היו שדה שטוח של --paper-deep. */
    assert.match(html, /\.prog\{[^}]*var\(--well\)/, 'פס ההתקדמות חזר להיות שטוח');
  });

  test('ההרמה בשימוש על משטחים שהיו בלי צל', () => {
    const n = (html.match(/var\(--lift-[12]\)/g) || []).length;
    assert.ok(n >= 3, `טוקני ההרמה בשימוש ${n} פעמים בלבד`);
  });
});

describe('גרעין הנייר', () => {

  test('קיים, ואינו יכול לחסום לחיצה', () => {
    const m = html.match(/body::before\{[^}]*\}/);
    assert.ok(m, 'גרעין הנייר נעלם');
    assert.match(m[0], /pointer-events:none/, 'הגרעין יכול לחטוף לחיצות');
    assert.match(m[0], /z-index:-1/, 'הגרעין אינו מאחורי התוכן');
    const op = m[0].match(/opacity:([\d.]+)/);
    assert.ok(op && parseFloat(op[1]) <= .06,
      `אטימות ${op && op[1]} · מעל .06 הגרעין נקרא כרעש ולא כמרקם`);
  });

  test('⛔ בלי בקשת רשת ובלי צבע חדש', () => {
    const m = html.match(/body::before\{[^}]*\}/)[0];
    assert.match(m, /url\("data:image\/svg\+xml/, 'הגרעין נטען מהרשת · חייב להיות data URI');
    assert.ok(!/#[0-9a-fA-F]{3,6}|rgb\(/.test(m),
      'הגרעין מכניס צבע · הוא חייב להיות אלפא בלבד, הפלטה נעולה');
  });
});
