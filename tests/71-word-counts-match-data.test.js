'use strict';
/* מסך ההרשמה מכריז כמה מילים יש במאגר. הבדיקה הזאת מוודאת שהמספר נכון.
 *
 * מה קרה
 * ------
 * `index.html` הציג למשתמשים "1,719 מילים בעברית · 3,900 באנגלית" בזמן
 * ש-`data.js` החזיק 1,717 ו-`data-en.js` החזיק 3,946. פער של ‎-2 ושל ‎+46,
 * בטקסט שכל נרשם חדש קורא לפני שהוא פותח חשבון.
 *
 * איש לא הכניס את השגיאה. המספרים נכתבו נכון פעם אחת, ואז המאגר גדל ומישהו
 * לא חזר לעדכן · כי שום דבר לא אילץ אותו. **מספר קשיח הוא תאריך תפוגה נסתר**,
 * וזה בדיוק מה שהבדיקה הזאת מבטלת: מהיום, כל שינוי במאגר שלא מלווה בעדכון
 * המסך מפיל את החבילה.
 *
 * למה השוואה ולא חישוב
 * --------------------
 * אפשר היה למחוק את המספרים מ-HTML ולמלא אותם ב-JS מ-`UNIT_DATA`. לא נעשה
 * כאן משתי סיבות: מסך ההרשמה מוצג לפני שקובצי המאגר בהכרח נטענו, ומספר שנעלם
 * לרגע גרוע ממספר נכון; ושינוי כזה נוגע ב-`app.js` שסשן אחר עובד עליו.
 * ההשוואה נותנת את אותה הגנה בלי אף אחד מהשניים.
 *
 * ⚠ הבדיקה קוראת את המספר מה-HTML בעצמה ואינה מחזיקה עותק שלו. אין כאן
 * מספר קשיח שני שיכול להתיישן בתורו.
 */

const { test } = require('node:test');
const assert = require('node:assert');
const fs = require('fs');
const path = require('path');

const שורש = path.join(__dirname, '..');

function ספור(קובץ, שם) {
  const g = {};
  global.window = g;
  delete require.cache[require.resolve(path.join(שורש, קובץ))];
  require(path.join(שורש, קובץ));
  const o = g[שם];
  assert.ok(o && typeof o === 'object', `${קובץ} לא הגדיר את window.${שם}`);
  return Object.keys(o).reduce((s, u) => s + (Array.isArray(o[u]) ? o[u].length : 0), 0);
}

const html = fs.readFileSync(path.join(שורש, 'index.html'), 'utf8');

/* השורה מזוהה לפי ה-id ולא לפי מספר שורה: מספר שורה זז בכל עריכה. */
const m = html.match(/id="authSub"[^>]*>([^<]*)</);

test('שורת אוצר המילים במסך ההרשמה קיימת', () => {
  assert.ok(m, 'לא נמצא <p id="authSub"> ב-index.html. אם המזהה השתנה -- לעדכן כאן.');
});

test('המספרים במסך ההרשמה תואמים למאגר בפועל', () => {
  const מוצג = m[1];
  const מספרים = (מוצג.match(/[\d,]+/g) || []).map(s => Number(s.replace(/,/g, '')));
  assert.strictEqual(מספרים.length, 2,
    `ציפיתי לשני מספרים בשורה, נמצאו ${מספרים.length}: "${מוצג}"`);

  const [עברית, אנגלית] = מספרים;
  const עברית_בפועל  = ספור('data.js', 'UNIT_DATA');
  const אנגלית_בפועל = ספור('data-en.js', 'UNIT_DATA_EN');

  assert.strictEqual(עברית, עברית_בפועל,
    `מסך ההרשמה מכריז ${עברית} מילים בעברית, ו-data.js מחזיק ${עברית_בפועל}. לעדכן את index.html.`);
  assert.strictEqual(אנגלית, אנגלית_בפועל,
    `מסך ההרשמה מכריז ${אנגלית} מילים באנגלית, ו-data-en.js מחזיק ${אנגלית_בפועל}. לעדכן את index.html.`);
});

/* ⚠ שיניים. בדיקה שעוברת בלי שהוכח שהיא מסוגלת ליפול אינה עדות.
   כאן מוזרקת שורה שבורה בכוונה, וההשוואה חייבת לתפוס אותה. */
test('לבדיקה יש שיניים · שורה עם מספר שגוי נתפסת', () => {
  const שבור = html.replace(/id="authSub"[^>]*>[^<]*</, 'id="authSub">1 מילים בעברית · 2 באנגלית.<');
  const m2 = שבור.match(/id="authSub"[^>]*>([^<]*)</);
  const מספרים = (m2[1].match(/[\d,]+/g) || []).map(s => Number(s.replace(/,/g, '')));
  assert.notStrictEqual(מספרים[0], ספור('data.js', 'UNIT_DATA'),
    'ההשוואה לא תפסה מספר שגוי שהוזרק בכוונה -- היא בודקת את הדבר הלא-נכון');
});
