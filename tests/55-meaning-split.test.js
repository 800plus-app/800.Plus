'use strict';
/* פיצול הפירוש · תשובה נכונה אחת מספיקה.
 *
 * מה חגי דיווח (5.8.2026, חשוב ודחוף 10)
 * ---------------------------------------
 * "כאשר יש בתשובות כמה אופציות לא צריך לכתוב פסיק ביניהן. יש לי כמה דוגמאות שכתבתי
 * תשובה נכונה אבל היה צריך לכתוב פסיק ולהוסיף עוד מילה · אבל זה לא נכון, כי כבר רשמתי
 * את אחד הפירושים של המילה. צריך לדייק את מנגנון התשובות."
 *
 * מה נמצא במדידה
 * ---------------
 * הפיצול הכיר בפסיק, נקודה-פסיק, לוכסן, קו אנכי ומקף-מוקף-רווחים · אבל לא בנקודה
 * ולא בנקודתיים. מתוך 5,662 הפירושים, 40 מכילים ":" ו-13 מכילים ".", ובהם הפירוש
 * השני מגיע אחרי מילת קישור:
 *
 *     נָבוּב :: חלול, ריק. בהשאלה: ריקני, שטחי
 *
 * המקטע שנוצר היה "ריק בהשאלה ריקני" · מחרוזת שאיש אינו מקליד · ולכן גם "ריק" וגם
 * "ריקני" נדחו, למרות ששניהם פירושים נכונים ומופיעים על המסך.
 *
 * המקרה הקשה, וזה שהופך את זה מאי-נוחות לבאג
 * --------------------------------------------
 *     תַּתְרָן :: נטול חוש ריח. בהשאלה: חסר חוש הבחנה
 * כאן נדחו *שתי* התשובות האפשריות. בכיוון מילה→פירוש המילה הזאת לא הייתה ניתנת
 * לענייה בשום צורה · כל לומד שפגש אותה נכשל בה, ולתמיד.
 *
 * מה שנשמר במכוון
 * ----------------
 * שלושה שערים ממשיכים לחסום, וכל אחד נבדק כאן, כי הרחבת פיצול היא בדיוק הסוג של
 * שינוי שמקבל תשובות שגויות בדרך:
 *   1. סוגריים נמחקות לפני הפיצול, ולכן "(להיפך: נדיר)" אינו הופך את הניגוד לתשובה.
 *   2. מילה בודדת שנשלפה מתוך פירוש ארוך עדיין נדחית (התיקון מ-v‑קודם, ראה meaningMatch).
 *   3. מילות קישור ("וגם", "בהשאלה") נשארות כמקטע נפרד אחרי הפיצול על ":" · והן
 *      מסוננות, אחרת הקלדת "וגם" הייתה נחשבת נכונה.
 * ונקודה מפוצלת רק כשהיא בודדת, כדי ש"גם... וגם..." לא יתפרק.
 */

const { test, describe } = require('node:test');
const assert = require('node:assert');
const path = require('path');
const { loadApp, ROOT } = require('./_harness/sandbox.js');

const ctx = loadApp({ lang: 'he' });

function allEntries() {
  const prev = global.window;
  global.window = { };
  global.window.window = global.window;
  try {
    for (const f of ['data.js', 'data-en.js']) {
      delete require.cache[require.resolve(path.join(ROOT, f))];
      require(path.join(ROOT, f));
    }
    const out = [];
    for (const U of [global.window.UNIT_DATA, global.window.UNIT_DATA_EN])
      for (const k of Object.keys(U)) for (const r of U[k]) out.push({ term: r[0], meaning: r[1] });
    return out;
  } finally { global.window = prev; }
}

describe('פיצול הפירוש · פירוש אחד מספיק', () => {

  test('נקודה ונקודתיים מפצלות פירושים', () => {
    /* השוואה דרך join ולא deepStrictEqual: מערך שנבנה בתוך ארגז החול שייך ל-realm אחר,
       ו-deepStrictEqual דוחה אותו גם כשהתוכן זהה (ראה ההערה על plain() ב-sandbox.js). */
    assert.strictEqual(
      ctx.meaningSegs('חלול, ריק. בהשאלה: ריקני, שטחי').join('|'),
      'חלול|ריק|ריקני|שטחי');
  });

  test('המילה שלא הייתה ניתנת לענייה · שתי התשובות מתקבלות', () => {
    const m = 'נטול חוש ריח. בהשאלה: חסר חוש הבחנה';
    assert.ok(ctx.meaningMatch('נטול חוש ריח', m), '"נטול חוש ריח" נדחה');
    assert.ok(ctx.meaningMatch('חסר חוש הבחנה', m), '"חסר חוש הבחנה" נדחה');
  });

  test('פירוש שמגיע אחרי "וגם:" מתקבל בלי מילת הקישור', () => {
    const m = 'ריפא, הבריא; וגם: נרפא והתכסה ברקמה חדשה';
    assert.ok(ctx.meaningMatch('נרפא והתכסה ברקמה חדשה', m));
    assert.ok(ctx.meaningMatch('ריפא', m), 'הפירוש הראשון נשבר');
  });

  test('מילת קישור לבדה אינה תשובה', () => {
    /* השער שנוצר יחד עם הפיצול על ":" · בלעדיו "וגם" היה מקטע קביל בפני עצמו. */
    assert.ok(!ctx.meaningMatch('וגם', 'ריפא, הבריא; וגם: נרפא והתכסה ברקמה חדשה'),
      '"וגם" התקבל כתשובה נכונה');
    assert.ok(!ctx.meaningMatch('בהשאלה', 'חלול, ריק. בהשאלה: ריקני'),
      '"בהשאלה" התקבל כתשובה נכונה');
  });

  test('ניגוד בסוגריים עדיין נדחה', () => {
    assert.ok(!ctx.meaningMatch('נדיר', 'נפוץ, מצוי (להיפך: נדיר)'),
      'הניגוד התקבל כתשובה — הסוגריים הפסיקו להיחסם');
  });

  test('מילה שנשלפה מתוך דוגמה עדיין נדחית', () => {
    assert.ok(!ctx.meaningMatch('קרה', 'פוחד, חושש (אשר יגורתי בא - הדבר ממנו חששתי קרה)'),
      'מילה מתוך דוגמה התקבלה — התיקון הקודם נשבר');
  });

  test('"..." אינו מתפרק', () => {
    /* both... and... :: גם... וגם... · פיצול על כל נקודה היה הופך את זה לרסיסים. */
    assert.strictEqual(ctx.meaningSegs('גם... וגם...').length, 1,
      'שלוש הנקודות פוצלו, והפירוש התפרק');
  });

  test('על כל המאגר: כל מקטע שהאפליקציה מכירה בו · היא גם מקבלת', () => {
    const all = allEntries();
    assert.ok(all.length > 5000, 'המאגר לא נטען');
    const bad = [];
    for (const w of all) {
      const segs = ctx.meaningSegs(w.meaning);
      if (segs.length < 2) continue;
      for (const s of segs) if (!ctx.meaningMatch(s, w.meaning)) bad.push([w.term, s]);
    }
    assert.strictEqual(bad.length, 0,
      'מקטעים שהאפליקציה מייצרת ואז דוחה: ' + JSON.stringify(bad.slice(0, 5)));
  });

  test('על כל המאגר: מילת קישור קבילה רק כשהיא הפירוש כולו', () => {
    /* הניסוח הראשון כאן דרש אפס מקטעי-קישור בכלל, וזו הייתה הנחה שגויה שלי: שש מילים
       באנגלית · also→"גם", or→"או", vice versa→"להיפך", for example→"לדוגמה" · 
       הפירוש שלהן *הוא* מילת הקישור. הדרישה ההיא הפכה אותן לחסרות תשובה, ובדיקה 28
       תפסה את זה. הכלל הנכון הוא הקשרי: מילת קישור היא רעש כשהיא מקדימה פירוש אחר,
       והיא התשובה כשהיא לבדה. */
    const MARK = /^(?:ו?גמ|ו?בפרט|ו?בהשאלה|וכנ|כגונ|לדוגמה|למשל|להיפכ|או)$/;
    const bad = [];
    for (const w of allEntries()) {
      const segs = ctx.meaningSegs(w.meaning);
      if (segs.length < 2) continue;                 // פירוש יחיד · מותר שיהיה מילת קישור
      for (const s of segs) if (MARK.test(s)) bad.push([w.term, w.meaning, s]);
    }
    assert.strictEqual(bad.length, 0,
      'מילת קישור התקבלה כתשובה לצד פירושים אחרים: ' + JSON.stringify(bad.slice(0, 5)));
  });

  test('פירוש שכולו מילת קישור נשאר בר-מענה', () => {
    /* הרגרסיה עצמה, כבדיקה. */
    for (const [gloss, label] of [['גם', 'also'], ['או', 'or'], ['להיפך', 'vice versa'], ['לדוגמה', 'for example']])
      assert.ok(ctx.meaningMatch(gloss, gloss), `"${label}" (${gloss}) הפך לחסר תשובה`);
  });
});
