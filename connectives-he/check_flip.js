'use strict';
/* שער מילות ההיפוך · `flip` מצהיר על מילה שהופכת את כיוון המשפט.
 *
 *   node connectives-he/check_flip.js
 *
 * מה מוצהר ולמה זה חייב שער
 * -------------------------
 * שליש מהפריטים אמורים לכלול מילה שהופכת כיוון · שלילה («לא», «אין», «אינו»),
 * סייג («רק», «בלבד», «כמעט», «דווקא», «למעט») או תנאי בטל («אלמלא», «לולא»).
 * ‏`flip` מצהיר איזו מילה זו, וההסבר (`r`) אמור לומר שהיא המכריעה.
 *
 * ⛔ הכשל שהשער חוסם: הצהרה שאין לה כיסוי במשפט. כותב שכתב `flip: ["אינו"]`
 * ובמשפט כתוב «לא» יצר פריט שההסבר שלו מפנה למילה שאינה שם. זה לא נראה שבור
 * בקריאה מהירה, והוא שובר בדיוק את מה שהיחידה באה ללמד.
 *
 * ⚠ ל-JS אין `\b` שעובד על עברית · `\b` בנוי על `\w` שהוא ASCII בלבד. ולכן
 * ‏`/\bלא\b/` היה מדווח «נמצא» על «לאחר» ו«נמצא» על «מלאכה». ההשוואה כאן היא
 * טוקן מול טוקן (`lib_conn.phraseIn`), ומילה שמופיעה רק כתת-מחרוזת נופלת.
 *
 * ⚠ מה השער **אינו** בודק: אם המילה באמת הופכת את הכיוון בהקשר הזה, ואם `r`
 * באמת מסביר אותה. אלה קריאה אנושית.
 */
const L = require('./lib_conn.js');

/* המילים שהיחידה מגדירה כהופכות כיוון · הרשימה כאן היא **לקסיקון הצפוי**
   בלבד, ומשמשת לבקרה חיובית (כמה פריטים נושאים היפוך) ולהתרעה על מילה
   שהוצהרה כהופכת ואינה מוכרת. ⛔ היא **אינה** רשימת מילות הקישור של היחידה
   ואינה מחליפה את `words.json` · אלה שני נכסים שונים. */
const FLIP_LEX = new Set([
  'לא', 'אין', 'אינו', 'אינה', 'אינם', 'אינן', 'מעולם', 'בלתי', 'ללא',
  'רק', 'בלבד', 'כמעט', 'דווקא', 'למעט', 'אלא', 'זולת', 'פרט',
  'אלמלא', 'לולא', 'אילולא', 'אלמלי',
]);

const { items, files, broken, dir } = L.loadBatches();
const findings = broken.slice();
let withFlip = 0, phrases = 0;
const unknown = new Set();

for (const it of items) {
  const add = m => findings.push(`${it.src} · ${m}`);
  if (!Array.isArray(it.flip)) { add('flip אינו מערך'); continue; }
  if (it.flip.length) withFlip++;

  for (const f of it.flip) {
    if (typeof f !== 'string' || !f.trim()) { add('איבר ריק ב-flip'); continue; }
    phrases++;
    if (!L.phraseIn(it.s, f)) add(`"${f}" מוצהרת ב-flip ואינה מופיעה מילולית במשפט`);
    const t = L.tokens(f);
    if (t.length === 1 && !FLIP_LEX.has(t[0])) unknown.add(t[0]);
  }
}

/* ── בקרה חיובית ─────────────────────────────────────────────────────────
   ⛔ בלי שתי השורות האלה, מנה שבה כל `flip` ריק הייתה מדווחת «0 ממצאים»
   בזכות זה שלא נבדק דבר. */
const share = items.length ? Math.round(100 * withFlip / items.length) : 0;
const notes = [
  `מנות: ${files.join(', ') || '(אין)'} · ${dir}`,
  `פריטים עם מילה הופכת: ${withFlip}/${items.length} (${share}%) · ${phrases} הצהרות נבדקו`,
];
if (!phrases) notes.push('⚠ אף הצהרת flip לא נבדקה — השער עבר על ריק, וזה אינו כיסוי.');
if (share < 25 && items.length >= 20)
  notes.push(`⚠ היעד בתוכנית הוא כשליש מהפריטים · כרגע ${share}%.`);
if (unknown.size)
  notes.push(`ℹ מילים שהוצהרו כהופכות ואינן בלקסיקון: ${[...unknown].join(', ')}`);
notes.push('⚠ נבדקה נוכחות מילולית בלבד. אם המילה באמת הופכת את הכיוון כאן,');
notes.push('   ואם r מסביר אותה — קריאה אנושית, לא נמדד כאן.');

process.exit(L.verdict('שער מילות ההיפוך · מילות קישור', items.length, findings, notes));
