/** ימים שנותרו עד המועד, נכון לרגע הרינדור. */
export const daysToExam = () => {
  const exam = new Date(EXAM_DATE + "T00:00:00");
  const now = new Date();
  now.setHours(0, 0, 0, 0);
  return Math.max(0, Math.round((exam.getTime() - now.getTime()) / 86400000));
};

